
const memes = [
    "Я не убиваю людей я делаю их статистикой.",
    "Раслабься. Боль-это просто слабость, выходящая наружу.",
    "У меня нет вредных привычек. У меня есть вредные таланты. Разница большая.",
    "Мой утренний ретуал: прснуться, пожелеть об этом, пойти дальше.",
    "Кто сказал, что супергерои должны быть серьёзными?",
    "Ты выглядишь как человек, который прочитает инструкцию. Мне жаль тебя.",
    "Я бы согласился, но мне лень.",
    "Я не спорю я просто громко прав."
];

function newMeme() {
    const text = document.getElementById("meme-text");

    let randomMeme = memes[
        Math.floor(Math.random() * memes.length)
    ];

    text.style.opacity = 0;

    setTimeout(() => {
        text.textContent = randomMeme;
        text.style.opacity = 1;
    }, 200);
}